const langButton = document.getElementById("langBtn");
const hamburgerButton = document.getElementById("hamburgerBtn");
const mobileMenu = document.getElementById("mobileMenu");
const contactForm = document.getElementById("contactForm");
const formSuccess = document.getElementById("formSuccess");

langButton?.addEventListener("click", toggleLang);
hamburgerButton?.addEventListener("click", toggleMenu);
contactForm?.addEventListener("submit", sendForm);
mobileMenu?.querySelectorAll("a").forEach((link) => {
  link.addEventListener("click", closeMenu);
});

function toggleLang() {
  lang = lang === "fr" ? "en" : "fr";
  document.getElementById("langBtn").textContent = lang === "fr" ? "EN" : "FR";
  const i = lang === "fr" ? 0 : 1;
  Object.keys(T).forEach((id) => {
    const el = document.getElementById(id);
    if (!el) return;
    if (
      el.tagName === "A" ||
      el.tagName === "BUTTON" ||
      el.tagName === "H1" ||
      el.tagName === "P" ||
      el.tagName === "H2" ||
      el.tagName === "H3" ||
      el.tagName === "SPAN" ||
      el.tagName === "LI" ||
      el.tagName === "DIV"
    ) {
      el.innerHTML = T[id][i];
    }
  });
}

function sendForm(event) {
  event.preventDefault();
  const form = event.currentTarget;
  const nom = document.getElementById("f-nom").value;
  const boutique = document.getElementById("f-boutique").value;
  const contact = document.getElementById("f-contact").value;
  const service = document.getElementById("f-service").value;
  const msg = document.getElementById("f-msg").value;
  const subject = encodeURIComponent("Demande de contact — " + service);
  const body = encodeURIComponent(
    "Nom: " +
      nom +
      "\nBoutique: " +
      boutique +
      "\nContact: " +
      contact +
      "\nService: " +
      service +
      "\n\nMessage:\n" +
      msg,
  );
  window.open(
    "mailto:dossouodette57@gmail.com?subject=" + subject + "&body=" + body,
    "_blank",
  );
  formSuccess.classList.add("visible");
  form.reset();
  setTimeout(() => formSuccess.classList.remove("visible"), 6000);
}

function toggleMenu() {
  const isOpen = mobileMenu.classList.toggle("open");
  hamburgerButton.classList.toggle("open", isOpen);
}

function closeMenu() {
  mobileMenu.classList.remove("open");
  hamburgerButton.classList.remove("open");
}
